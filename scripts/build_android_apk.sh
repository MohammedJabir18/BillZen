#!/usr/bin/env bash
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
ROOT_DIR="$(cd "$SCRIPT_DIR/.." && pwd)"

TOOLCHAIN_DIR="/home/jabir/.android-toolchain"
export JAVA_HOME="$TOOLCHAIN_DIR/jdk"
export ANDROID_HOME="$TOOLCHAIN_DIR/android-sdk"
export NDK_HOME="$ANDROID_HOME/ndk/26.1.10909125"
export PATH="$JAVA_HOME/bin:$ANDROID_HOME/cmdline-tools/latest/bin:$ANDROID_HOME/platform-tools:$ANDROID_HOME/build-tools/36.0.0:$ANDROID_HOME/build-tools/34.0.0:$PATH"

KEYSTORE="${BILLZEN_KEYSTORE_PATH:-$TOOLCHAIN_DIR/billzen-beta.keystore}"
KEY_ALIAS="${BILLZEN_KEY_ALIAS:-billzen}"
KEY_PASS="${BILLZEN_KEYSTORE_PASS:-}"

# Support 16 KB page alignment for Android 15+ native libraries
export RUSTFLAGS="-C link-arg=-z -C link-arg=max-page-size=16384 ${RUSTFLAGS:-}"

echo "=== BillZen Android Beta Build Workflow ==="
echo "Java Home:    $JAVA_HOME"
echo "Android Home: $ANDROID_HOME"
echo "NDK Home:     $NDK_HOME"
echo "Rustflags:    $RUSTFLAGS"

if [ ! -d "$NDK_HOME" ]; then
    echo "Error: NDK 26.1 not found at $NDK_HOME"
    exit 1
fi

if [ -z "$KEY_PASS" ] && [ -t 0 ]; then
    read -s -p "Enter keystore password: " KEY_PASS
    echo
fi

if [ -z "$KEY_PASS" ]; then
    echo "Error: BILLZEN_KEYSTORE_PASS environment variable is required for signing"
    exit 1
fi

cd "$ROOT_DIR"

# Clean previous build artifacts to prevent stale fallbacks
BUILD_DIR="$ROOT_DIR/src-tauri/gen/android/app/build/outputs/apk"
rm -rf "$BUILD_DIR"

# Authoritative versioning
export BILLZEN_VERSION_CODE="${BILLZEN_VERSION_CODE:-1003}"
export BILLZEN_VERSION_NAME="${BILLZEN_VERSION_NAME:-0.1.0}"

TARGET_ARCH="${1:-aarch64}"
if [ "$TARGET_ARCH" = "x86_64" ]; then
    ABI_NAME="x86_64"
    SIGNED_APK="$ROOT_DIR/dist-android/billzen-test-v0.1.0-x86_64.apk"
elif [ "$TARGET_ARCH" = "aarch64" ] || [ "$TARGET_ARCH" = "arm64-v8a" ]; then
    TARGET_ARCH="aarch64"
    ABI_NAME="arm64-v8a"
    SIGNED_APK="$ROOT_DIR/dist-android/billzen-beta-v0.1.0-arm64-v8a.apk"
else
    echo "ERROR: Unsupported target arch $TARGET_ARCH"
    exit 1
fi

echo "Writing authoritative version metadata to tauri.properties..."
cat <<EOF > "$ROOT_DIR/src-tauri/gen/android/app/tauri.properties"
// THIS IS AN AUTOGENERATED FILE. DO NOT EDIT THIS FILE DIRECTLY.
tauri.android.versionName=$BILLZEN_VERSION_NAME
tauri.android.versionCode=$BILLZEN_VERSION_CODE
EOF

# Ensure frontend build passes
echo "--- 1. Building frontend assets ---"
npm run build

# Run Tauri Android Build
echo "--- 2. Building Android native binary & APK via Tauri CLI for $TARGET_ARCH ($ABI_NAME) ---"
npx tauri android build --apk --target "$TARGET_ARCH" --ci

# Locate generated APK
echo "Build outputs found in $BUILD_DIR:"
find "$BUILD_DIR" -type f -name "*.apk"

OUTPUT_DIR="$ROOT_DIR/dist-android"
mkdir -p "$OUTPUT_DIR"

# Select exact release variant and strictly reject debug fallback
RAW_APK=$(find "$BUILD_DIR" -type f \( -name "*${ABI_NAME}*release*.apk" -o -name "*universal*release*.apk" -o -name "*release*.apk" \) | grep -v "unaligned" | head -n 1 || true)

if [ -z "$RAW_APK" ]; then
    echo "ERROR: Release APK variant was not produced in $BUILD_DIR! (Debug fallback is strictly rejected)"
    exit 1
fi

echo "Selected Release APK: $RAW_APK"
rm -f "$SIGNED_APK"

# Align and sign using the designated BillZen Beta Keystore with 16KB page alignment
echo "--- 3. Aligning and Signing APK with BillZen Beta Keystore (16KB page-aligned) ---"
ALIGNED_APK="/tmp/billzen-aligned.apk"
rm -f "$ALIGNED_APK"
zipalign -v -f -P 16 4 "$RAW_APK" "$ALIGNED_APK"

apksigner sign \
    --ks "$KEYSTORE" \
    --ks-key-alias "$KEY_ALIAS" \
    --ks-pass "pass:$KEY_PASS" \
    --out "$SIGNED_APK" \
    "$ALIGNED_APK"
rm -f "$ALIGNED_APK"

echo "--- 4. Verifying APK Signature & Certificate Identity ---"
apksigner verify --verbose "$SIGNED_APK"

CERT_OUTPUT=$(apksigner verify --print-certs "$SIGNED_APK")
echo "$CERT_OUTPUT"
if ! echo "$CERT_OUTPUT" | grep -q "CN=BillZen Beta"; then
    echo "ERROR: APK certificate subject does not match 'CN=BillZen Beta'!"
    exit 1
fi
if ! echo "$CERT_OUTPUT" | grep -qi "becf5a076bb17161c01f992a0d4561ede07394fd413407084e83e7f0325d25e4"; then
    echo "ERROR: APK certificate SHA-256 fingerprint mismatch!"
    exit 1
fi
echo "Certificate identity verified successfully."

echo "--- 5. Verifying 16 KB Packaging Zipalign ---"
zipalign -c -v -P 16 4 "$SIGNED_APK"
echo "APK 16 KB packaging alignment verified."

echo "--- 6. Verifying 16 KB ELF Page-Size Alignment ---"
TMP_LIB_DIR="/tmp/billzen_lib_check_$$"
mkdir -p "$TMP_LIB_DIR"
unzip -p "$SIGNED_APK" "lib/$ABI_NAME/libbillzen_lib.so" > "$TMP_LIB_DIR/libbillzen_lib.so"

READELF_BIN="$NDK_HOME/toolchains/llvm/prebuilt/linux-x86_64/bin/llvm-readelf"
if [ ! -x "$READELF_BIN" ]; then
    READELF_BIN="readelf"
fi

echo "Analyzing ELF LOAD segments with $READELF_BIN..."
LOAD_SEGMENTS=$("$READELF_BIN" -l "$TMP_LIB_DIR/libbillzen_lib.so" | grep "LOAD")
echo "$LOAD_SEGMENTS"

# Ensure all LOAD segments have Align 0x4000 (16384 bytes) or greater
NON_16K=$(echo "$LOAD_SEGMENTS" | awk '{print $NF}' | grep -v -E "0x[4-9a-fA-F][0-9a-fA-F]{3}|0x[1-9a-fA-F][0-9a-fA-F]{4}" || true)
if [ -n "$NON_16K" ]; then
    echo "ERROR: Detected ELF LOAD segment with alignment less than 16 KB (0x4000):"
    echo "$NON_16K"
    rm -rf "$TMP_LIB_DIR"
    exit 1
fi
echo "16 KB ELF page alignment verified across all LOAD segments."
rm -rf "$TMP_LIB_DIR"

echo "--- 7. Verifying Offline Resources in APK & Native Binary ---"
unzip -l "$SIGNED_APK" | grep "assets/tauri.conf.json" > /dev/null || { echo "ERROR: assets/tauri.conf.json missing in APK!"; exit 1; }
unzip -l "$SIGNED_APK" | grep "lib/$ABI_NAME/libbillzen_lib.so" > /dev/null || { echo "ERROR: Native library missing in APK!"; exit 1; }

TMP_RES_DIR="/tmp/billzen_res_check_$$"
mkdir -p "$TMP_RES_DIR"
unzip -p "$SIGNED_APK" "lib/$ABI_NAME/libbillzen_lib.so" > "$TMP_RES_DIR/libbillzen_lib.so"

if ! strings "$TMP_RES_DIR/libbillzen_lib.so" | grep "assets/index-" > /dev/null; then
    echo "ERROR: Compiled JS/CSS assets missing in embedded native binary!"
    rm -rf "$TMP_RES_DIR"
    exit 1
fi

if ! strings "$TMP_RES_DIR/libbillzen_lib.so" | grep "NotoSans" > /dev/null; then
    echo "ERROR: Offline local fonts missing in embedded native binary!"
    rm -rf "$TMP_RES_DIR"
    exit 1
fi
rm -rf "$TMP_RES_DIR"
echo "Offline assets and local fonts verified inside native binary."

echo "--- 8. Reading Actual Metadata from Built APK & Asserting Invariants ---"
BADGING_OUTPUT=$(aapt dump badging "$SIGNED_APK")

ACTUAL_PACKAGE_ID=$(echo "$BADGING_OUTPUT" | grep "^package:" | sed -E "s/^package: name='([^']+)'.*/\1/")
ACTUAL_VERSION_CODE=$(echo "$BADGING_OUTPUT" | grep "^package:" | sed -E "s/.*versionCode='([^']+)'.*/\1/")
ACTUAL_VERSION_NAME=$(echo "$BADGING_OUTPUT" | grep "^package:" | sed -E "s/.*versionName='([^']+)'.*/\1/")
ACTUAL_MIN_SDK=$(echo "$BADGING_OUTPUT" | grep "^sdkVersion:" | sed -E "s/sdkVersion:'([^']+)'.*/\1/")
ACTUAL_TARGET_SDK=$(echo "$BADGING_OUTPUT" | grep "^targetSdkVersion:" | sed -E "s/targetSdkVersion:'([^']+)'.*/\1/")
ACTUAL_ABI=$(echo "$BADGING_OUTPUT" | grep "^native-code:" | sed -E "s/native-code: '([^']+)'.*/\1/")

EXPECTED_PACKAGE_ID="com.billzen.desktop"
EXPECTED_VERSION_CODE="$BILLZEN_VERSION_CODE"
EXPECTED_VERSION_NAME="$BILLZEN_VERSION_NAME"
EXPECTED_MIN_SDK="24"
EXPECTED_TARGET_SDK="34"
EXPECTED_ABI="$ABI_NAME"

if [ "$ACTUAL_PACKAGE_ID" != "$EXPECTED_PACKAGE_ID" ]; then
    echo "ERROR: Package ID mismatch: expected $EXPECTED_PACKAGE_ID, got $ACTUAL_PACKAGE_ID"
    exit 1
fi

if [ "$ACTUAL_VERSION_CODE" != "$EXPECTED_VERSION_CODE" ]; then
    echo "ERROR: Version code mismatch: expected $EXPECTED_VERSION_CODE, got $ACTUAL_VERSION_CODE"
    exit 1
fi

if [ "$ACTUAL_VERSION_NAME" != "$EXPECTED_VERSION_NAME" ]; then
    echo "ERROR: Version name mismatch: expected $EXPECTED_VERSION_NAME, got $ACTUAL_VERSION_NAME"
    exit 1
fi

if [ "$ACTUAL_MIN_SDK" != "$EXPECTED_MIN_SDK" ]; then
    echo "ERROR: Min SDK mismatch: expected $EXPECTED_MIN_SDK, got $ACTUAL_MIN_SDK"
    exit 1
fi

if [ "$ACTUAL_TARGET_SDK" != "$EXPECTED_TARGET_SDK" ]; then
    echo "ERROR: Target SDK mismatch: expected $EXPECTED_TARGET_SDK, got $ACTUAL_TARGET_SDK"
    exit 1
fi

if [ "$ACTUAL_ABI" != "$EXPECTED_ABI" ]; then
    echo "ERROR: ABI mismatch: expected $EXPECTED_ABI, got $ACTUAL_ABI"
    exit 1
fi

SHA256=$(sha256sum "$SIGNED_APK" | awk '{print $1}')
FILESIZE=$(ls -lh "$SIGNED_APK" | awk '{print $5}')

echo "=========================================="
echo "Android Beta Release APK Verified & Ready!"
echo "Location:     $SIGNED_APK"
echo "Size:         $FILESIZE"
echo "SHA-256:      $SHA256"
echo "Package ID:   $ACTUAL_PACKAGE_ID"
echo "Version Name: $ACTUAL_VERSION_NAME"
echo "Version Code: $ACTUAL_VERSION_CODE"
echo "ABI:          $ACTUAL_ABI"
echo "Min SDK:      $ACTUAL_MIN_SDK"
echo "Target SDK:   $ACTUAL_TARGET_SDK"
echo "=========================================="
