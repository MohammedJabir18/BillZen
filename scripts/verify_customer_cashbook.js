import assert from 'node:assert/strict';
import { spawn } from 'node:child_process';
import { chromium } from 'playwright';
import fs from 'node:fs/promises';
import path from 'node:path';
import { navigateToAppTab } from './lib/navigation.js';

const url = 'http://127.0.0.1:4193';
const server = spawn('node', ['node_modules/vite/bin/vite.js', '--host', '127.0.0.1', '--port', '4193', '--strictPort'], { stdio: 'ignore' });
let browser;
try {
  for (let i = 0; i < 100; i++) {
    try { if ((await fetch(url)).ok) break; } catch {}
    await new Promise(resolve => setTimeout(resolve, 100));
  }
  browser = await chromium.launch({ channel: 'chrome', headless: true, args: ['--no-sandbox'] });
  const page = await browser.newPage({ viewport: { width: 1280, height: 900 } });
  page.setDefaultTimeout(10000);
  const artifacts = path.resolve('test_artifacts/customer-cashbook');
  await fs.mkdir(artifacts, { recursive: true });
  await page.goto(url + '/?tab=customers');
  await page.evaluate(async () => {
    const api = await import('/src/adapters/tauri.ts');
    const settings = await api.getBusinessSettings();
    await api.updateBusinessSettings({ ...settings, is_setup_completed: true, guide_status: 'completed' });
    await api.createCustomer({ name: 'Cash customer', country: 'India' });
  });
  await page.reload();
  const row = page.getByTestId('customer-row-Cash customer').filter({ visible: true });
  await row.getByRole('button', { name: 'Cash history', exact: true }).click({ timeout: 5000 });
  await page.getByTestId('customer-cash-history').waitFor();
  assert.equal(await page.getByTestId('customer-net-movement').textContent(), '₹ 0.00');
  assert.equal(await page.getByText('Amount due', { exact: true }).count(), 0);
  await page.getByTestId('customer-receive-money').click();
  await page.getByTestId('select-voucher-party').waitFor();
  assert.ok(await page.getByTestId('select-voucher-party').inputValue());
  assert.equal(await page.getByTestId('select-voucher-party').isDisabled(), true);
  const accountId = await page.getByTestId('select-voucher-account').inputValue();
  const originalDay = await page.getByTestId('input-voucher-date').inputValue();
  const prior = new Date(originalDay + 'T12:00:00Z');
  prior.setUTCDate(prior.getUTCDate() - 1);
  const transactionDate = prior.toISOString().slice(0, 10);
  await page.getByTestId('input-voucher-date').fill(transactionDate);
  await page.getByTestId('input-voucher-amount').fill('120');
  await page.getByTestId('btn-submit-voucher').click();
  await page.getByTestId('select-voucher-party').waitFor({ state: 'hidden' });
  await navigateToAppTab(page, 'customers');
  await page.getByTestId('customer-row-Cash customer').filter({ visible: true }).getByRole('button', { name: 'Cash history', exact: true }).click();
  await page.getByTestId('customer-net-movement').filter({ hasText: '120.00' }).waitFor();
  await page.getByLabel('Start date', { exact: true }).fill(transactionDate);
  await page.getByLabel('End date', { exact: true }).fill(transactionDate);
  await page.getByTestId('customer-cash-history').locator('select').first().selectOption(accountId);
  await page.getByTestId('customer-net-movement').filter({ hasText: '120.00' }).waitFor();
  await page.getByRole('button', { name: /View in Reports:/ }).click();
  await page.getByTestId('report-party-select').waitFor({ timeout: 5000 });
  assert.ok(await page.getByTestId('report-party-select').inputValue());
  assert.equal(await page.getByTestId('report-custom-start-date').inputValue(), transactionDate);
  assert.equal(await page.getByTestId('report-custom-end-date').inputValue(), transactionDate);
  assert.equal(await page.getByTestId('report-account-select').inputValue(), accountId);
  await page.getByTestId('report-matching-banner').filter({ hasText: '120.00' }).waitFor();
  const downloadPromise = page.waitForEvent('download');
  await page.getByTestId('btn-export-csv').click();
  const download = await downloadPromise;
  const csv = await fs.readFile(await download.path(), 'utf8');
  assert.match(csv, /Cash customer/);
  assert.match(csv, /120.00/);
  assert.ok(csv.includes(transactionDate));
  const before = await page.evaluate(async () => {
    const api = await import('/src/adapters/cashbook.ts');
    const catalog = await import('/src/adapters/tauri.ts');
    const customer = (await catalog.getCustomers({}))[0];
    const parties = await api.getCashbookParties();
    const party = parties.find(p => p.customer_id === customer.id);
    const ledger = await api.getCashbookLedger({ party_id: party.id });
    const receipt = ledger.entries.find(e => !e.voucher.is_reversal).voucher;
    await api.postCashbookVoucher({ account_id: receipt.account_id, party_id: party.id, direction: 'outflow', classification: 'refund', payment_method: 'cash', amount_minor: 2000, business_date: receipt.business_date, idempotency_key: crypto.randomUUID() });
    return { receiptId: receipt.id, stock: await catalog.getProducts({}) };
  });
  await page.reload();
  await navigateToAppTab(page, 'customers');
  await page.getByTestId('customer-row-Cash customer').filter({ visible: true }).getByRole('button', { name: 'Cash history', exact: true }).click();
  await page.getByTestId('customer-net-movement').filter({ hasText: '100.00' }).waitFor();
  assert.equal(await page.getByTestId('customer-cash-received').textContent(), '₹ 120.00');
  assert.equal(await page.getByTestId('customer-cash-paid').textContent(), '₹ 20.00');
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await navigateToAppTab(page, 'cashbook');
  await page.getByTestId('cashbook-ledger-table').getByRole('row').filter({ hasText: '120.00' }).getByTestId('btn-reverse-voucher').click();
  await page.getByTestId('btn-confirm-reversal').click();
  await page.getByTestId('btn-confirm-reversal').waitFor({ state: 'hidden' });
  await navigateToAppTab(page, 'customers');
  await page.getByTestId('customer-row-Cash customer').filter({ visible: true }).getByRole('button', { name: 'Cash history', exact: true }).click();
  await page.getByTestId('customer-net-movement').filter({ hasText: '-20.00' }).waitFor();
  assert.equal(await page.getByTestId('customer-cash-history').locator('ol li').count(), 3);
  assert.ok(await page.getByText('Reversed original', { exact: true }).isVisible());
  assert.ok(await page.getByText('Reversal', { exact: true }).isVisible());
  const after = await page.evaluate(async () => {
    const api = await import('/src/adapters/cashbook.ts');
    const catalog = await import('/src/adapters/tauri.ts');
    const customer = (await catalog.getCustomers({}))[0];
    const party = (await api.getCashbookParties()).find(p => p.customer_id === customer.id);
    const ledger = await api.getCashbookLedger({ party_id: party.id });
    return { stock: await catalog.getProducts({}), balance: ledger.summary.total_cash_minor, entries: ledger.entries.length, legacyBalance: customer.current_balance_minor };
  });
  assert.deepEqual(after.stock, before.stock);
  assert.equal(after.entries, 3);
  assert.equal(after.balance, -2000);
  assert.equal(after.legacyBalance, 0);
  const future = new Date();
  future.setUTCFullYear(future.getUTCFullYear() + 1);
  await page.getByLabel('Start date', { exact: true }).fill(future.toISOString().slice(0, 10));
  await page.getByTestId('customer-net-movement').filter({ hasText: '₹ 0.00' }).waitFor();
  assert.equal(await page.getByTestId('customer-cash-history').locator('ol li').count(), 0);
  await page.getByLabel('Start date', { exact: true }).fill('');
  await page.getByTestId('customer-net-movement').filter({ hasText: '-20.00' }).waitFor();
  // Preserve explicit history date/account context through Reports navigation.
  await page.getByLabel('Start date', { exact: true }).fill('2020-01-01');
  await page.getByLabel('End date', { exact: true }).fill('2030-12-31');
  const historyAccount=page.getByTestId('customer-cash-history').getByRole('combobox').first();
  const historyAccountId=await historyAccount.locator('option').nth(1).getAttribute('value');
  await historyAccount.selectOption(historyAccountId);
  await page.getByTestId('customer-net-movement').filter({ hasText: '-20.00' }).waitFor();
  await page.getByRole('button', { name: /View in Reports:/ }).click();
  assert.equal(await page.getByTestId('report-custom-start-date').inputValue(),'2020-01-01');
  assert.equal(await page.getByTestId('report-custom-end-date').inputValue(),'2030-12-31');
  assert.equal(await page.getByTestId('report-account-select').inputValue(),historyAccountId);
  assert.equal(await page.getByTestId('report-period-custom').getAttribute('aria-pressed'),'true');
  await navigateToAppTab(page,'customers');
  await page.getByTestId('customer-row-Cash customer').filter({visible:true}).getByRole('button',{name:'Cash history',exact:true}).click();
  await page.getByTestId('customer-net-movement').filter({hasText:'-20.00'}).waitFor();
  await page.screenshot({ path: path.join(artifacts, 'desktop-light.png'), fullPage: true });
  await page.getByRole('button', { name: 'Close', exact: true }).click();
  await page.evaluate(() => { localStorage.setItem('billzen_ui_language', 'ar'); localStorage.setItem('billzen_appearance_pref', 'dark'); });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.emulateMedia({ reducedMotion: 'reduce', colorScheme: 'dark' });
  await page.reload();
  await navigateToAppTab(page, 'customers');
  const mobileRow = page.getByTestId('customer-row-Cash customer').filter({ visible: true });
  const historyButton = mobileRow.getByRole('button', { name: 'سجل النقد', exact: true });
  await historyButton.focus();
  await page.keyboard.press('Enter');
  await page.getByTestId('customer-net-movement').filter({ hasText: '-20.00' }).waitFor();
  assert.equal(await page.locator('html').getAttribute('dir'), 'rtl');
  const dialog = page.getByRole('dialog');
  const bounds = await dialog.locator('section').boundingBox();
  assert.ok(bounds.x >= 0 && bounds.x + bounds.width <= 391);
  await page.keyboard.press('Tab');
  assert.ok(await dialog.evaluate(element => element.contains(document.activeElement)));
  await page.screenshot({ path: path.join(artifacts, 'mobile-dark-arabic.png'), fullPage: true });
  await page.keyboard.press('Escape');
  await page.getByTestId('customer-cash-history').waitFor({ state: 'hidden' });
  console.log('Customer receipt → reload → history → party report → CSV → payment → reversal passed; desktop/light and mobile/dark/Arabic/reduced-motion/keyboard screenshots saved.');
} finally {
  await browser?.close();
  server.kill('SIGTERM');
}
